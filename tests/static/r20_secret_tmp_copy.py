# ─── R20 ─────────────────────────────────────────────────────────────────────────────────────
_ENV_RE = re.compile(r'^\.env(?:\.(?!(?:example|sample|dist|template|tmpl|in)$)[A-Za-z0-9_.-]+)?$')
_KEYFILE_RE = re.compile(r'^(?:id_(?:rsa|dsa|ecdsa|ed25519)|\.?pgpass|.*\.(?:key|p12|pfx|jks)|.*\.pgpass)$')
_SECRET_TOK = {'secret', 'secrets', 'credential', 'credentials', 'password', 'passwords', 'totp', 'private'}
SECRET_DIRS = ('/etc/tbox-v2',)
COPY_CMDS = {'cp', 'install', 'rsync'}
FILTER_CMDS = {'cat', 'sed', 'awk', 'gawk', 'mawk', 'grep', 'egrep', 'head', 'tail', 'sort', 'tr', 'cut',
               'envsubst', 'perl', 'uniq', 'tac'}


def secret_name(path):
    """경로 글자가 비밀 파일을 가리키면 짧은 이름(보고용), 아니면 None."""
    if not path:
        return None
    p = path.rstrip('/')
    for d in SECRET_DIRS:
        if p == d or p.startswith(d + '/'):
            return d + ('/…' if p != d else '')
    base = p.rsplit('/', 1)[-1]
    if not base:
        return None
    if _ENV_RE.match(base):
        return base
    if _KEYFILE_RE.match(base):
        return base
    toks = set(t.lower() for t in re.split(r'[^A-Za-z0-9]+', base) if t)
    if toks & _SECRET_TOK and not base.endswith(('.sh', '.php', '.py', '.md', '.js')):
        return base
    return None


def tail_lit(w):
    """단어의 마지막 확장 뒤 글자(경로 꼬리)."""
    tail = ''
    for p in w.parts:
        if p.k == 'lit':
            tail += p.v
        else:
            tail = ''
    return tail


class TmpCtx(object):
    """한 파일의 임시 뿌리 판정."""

    def __init__(self, sf):
        self.sf = sf
        self.roots = {}        # 변수 → (뿌리 id, mktemp 줄, 틀 바탕 이름 또는 None=고정 경로)
        self.assign_words = {}  # 변수 → [값 조각들]
        self.fparams = {}      # (함수, 위치 번호) → 뿌리 id
        self.falias = {}       # (함수, 지역 변수) → 위치 번호
        self.cleared = set()   # 복사 전에 rm -r 로 비운 변수(고정 경로)
        for c in sf.cmds:
            for w in self._assign_words(c):
                name, parts = sh_assign_parts(w)
                if not name:
                    continue
                self.assign_words.setdefault(name, []).append((parts, c))
                if c.func:
                    ps = [p for p in parts if not (p.k == 'lit' and p.v == '')]
                    if len(ps) == 1 and ps[0].k == 'pos' and isinstance(ps[0].v, int):
                        self.falias[(c.func, name)] = ps[0].v
        # mktemp 를 받은 변수
        for name, lst in self.assign_words.items():
            for parts, c in lst:
                subs = [p for p in parts if p.k == 'sub']
                if len(subs) == 1 and subs[0].sub is not None:
                    mk = self._mktemp_tmpl(subs[0].sub)
                    if mk is not None:
                        self.roots[name] = ('%s@%d' % (name, c.line), c.line, mk)
        # 한 단계 파생: D="$WORK/x" · 고정 /tmp 경로
        for _ in range(2):
            for name, lst in self.assign_words.items():
                if name in self.roots:
                    continue
                for parts, c in lst:
                    ps = [p for p in parts if not (p.k == 'lit' and p.v == '')]
                    if not ps:
                        continue
                    if ps[0].k == 'var' and ps[0].v in self.roots and ps[0].v != name:
                        self.roots[name] = self.roots[ps[0].v]
                        break
                    if ps[0].k == 'lit' and re.match(r'/(?:tmp|dev/shm)/', ps[0].v):
                        self.roots[name] = ('%s@%d' % (name, c.line), c.line, None)
                        break
        # 함수에 넘긴 임시 뿌리 → 그 함수의 위치 인자
        for c in sf.cmds:
            n0 = c.name()
            if not n0 or n0 not in sf.funcs:
                continue
            for i, w in enumerate(c.words[1:], 1):
                rid = self.root_of(w, c.func)
                if rid:
                    self.fparams.setdefault((n0, i), rid)
        # 복사 전에 비운 고정 경로(rm -rf "$T")
        for c in sf.cmds:
            ws = sh_effective(c.words)
            if ws and os.path.basename(ws[0].lit() or '') == 'rm' and \
                    any(re.fullmatch(r'-[a-zA-Z]*[rR][a-zA-Z]*', w.lit() or '') for w in ws[1:]):
                for w in ws[1:]:
                    ps = [p for p in w.parts if not (p.k == 'lit' and p.v == '')]
                    if len(ps) == 1 and ps[0].k == 'var':
                        self.cleared.add((ps[0].v, c.seq))

    @staticmethod
    def _assign_words(c):
        out = []
        if not c.words:
            out.extend(c.assigns)
        elif c.words[0].lit() in ('local', 'declare', 'typeset', 'export', 'readonly'):
            out.extend(w for w in c.words[1:] if SH_ASSIGN_RE.match(w.raw))
        return out

    @staticmethod
    def _mktemp_tmpl(sub):
        for c in sub.cmds:
            ws = sh_effective(c.words)
            if not ws or os.path.basename(ws[0].lit() or '') != 'mktemp':
                continue
            tmpl = None
            for w in ws[1:]:
                lt = w.lit()
                if lt is not None and lt.startswith('-'):
                    continue
                tl = tail_lit(w)
                tmpl = tl.rsplit('/', 1)[-1] if tl else None
            return tmpl if tmpl else 'tmp.XXXXXXXXXX'
        return None

    def root_of(self, w, func):
        """단어가 임시 뿌리 아래를 가리키면 뿌리 id."""
        ps = [p for p in w.parts if not (p.k == 'lit' and p.v == '')]
        if not ps:
            return None
        p0 = ps[0]
        if p0.k == 'var':
            if func and (func, p0.v) in self.falias:
                rid = self.fparams.get((func, self.falias[(func, p0.v)]))
                if rid:
                    return rid
            if p0.v in self.roots:
                return self.roots[p0.v][0]
            if p0.v == 'TMPDIR':
                return 'TMPDIR'
        if p0.k == 'pos' and isinstance(p0.v, int) and func:
            rid = self.fparams.get((func, p0.v))
            if rid:
                return rid
        if p0.k == 'lit' and re.match(r'/(?:tmp|dev/shm)/', p0.v):
            return 'literal:' + p0.v.split('/')[1]
        return None

    def root_info(self, rid):
        for name, (r, line, tmpl) in self.roots.items():
            if r == rid:
                return name, line, tmpl
        return None, None, None

    def secret_of(self, w, func, depth=0):
        s = secret_name(tail_lit(w) if w.lit() is None else w.lit())
        if s:
            return s
        ps = [p for p in w.parts if not (p.k == 'lit' and p.v == '')]
        if depth == 0 and len(ps) == 1 and ps[0].k == 'var':
            for parts, _c in self.assign_words.get(ps[0].v, []):
                s = secret_name(tail_lit(ShWord(parts, 0, '')))
                if s:
                    return s
        return None


def copy_pairs(c):
    """(원본 단어들, 대상 단어) — 복사·걸러 옮기기 명령이 아니면 None."""
    ws = sh_effective(c.words)
    if not ws:
        return None
    n0 = os.path.basename(ws[0].lit() or '')
    args = ws[1:]
    if n0 in COPY_CMDS:
        files, dest, k = [], None, 0
        while k < len(args):
            lt = args[k].lit()
            if lt is not None and lt.startswith('-') and lt != '-':
                if n0 == 'install' and lt in ('-m', '-o', '-g', '-S', '--mode', '--owner', '--group'):
                    k += 2
                    continue
                if lt in ('-t', '--target-directory') and k + 1 < len(args):
                    dest = args[k + 1]
                    k += 2
                    continue
                k += 1
                continue
            files.append(args[k])
            k += 1
        if dest is None:
            if len(files) < 2:
                return None
            dest = files.pop()
        return files, dest
    if n0 in FILTER_CMDS:
        dest = None
        for op, w in c.redirs:
            if op in ('>', '>>', '>|'):
                dest = w
        if dest is None:
            return None
        srcs = [w for op, w in c.redirs if op == '<']
        nonopt, k, has_e = [], 0, False
        while k < len(args):
            lt = args[k].lit()
            if lt is not None and lt.startswith('-') and lt != '-':
                if lt in ('-e', '-f', '--expression', '--file') and n0 in ('sed', 'perl', 'awk', 'gawk', 'mawk'):
                    has_e = True
                    k += 2
                    continue
                if lt in ('-v', '-F') and n0 in ('awk', 'gawk', 'mawk'):
                    k += 2
                    continue
                if n0 in ('grep', 'egrep') and lt in ('-e', '-f'):
                    has_e = True
                    k += 2
                    continue
                k += 1
                continue
            nonopt.append(args[k])
            k += 1
        if n0 in ('sed', 'awk', 'gawk', 'mawk', 'grep', 'egrep', 'perl') and not has_e and nonopt:
            nonopt = nonopt[1:]     # 첫 글은 스크립트·무늬
        return srcs + nonopt, dest
    return None


def has_stale_cleanup(sf, tmpl):
    """다음 실행이 옛 임시 폴더를 치우는 길(find -name 무늬 + 지우기 · rm -r 글롭)이 있나."""
    if not tmpl:
        return False
    filled = re.sub(r'X{3,}', lambda m: 'a' * len(m.group(0)), tmpl)
    rm_var = False
    finds = []
    for c in sf.cmds:
        ws = sh_effective(c.words)
        if not ws:
            continue
        n0 = os.path.basename(ws[0].lit() or '')
        lits = [w.lit() for w in ws[1:]]
        if n0 == 'rm' and any(re.fullmatch(r'-[a-zA-Z]*[rR][a-zA-Z]*', lt or '') for lt in lits):
            for w in ws[1:]:
                ps = [p for p in w.parts if not (p.k == 'lit' and p.v == '')]
                if ps and ps[-1].k == 'var' and len(ps) == 1:
                    rm_var = True
                tl = tail_lit(w)
                if '*' in tl or '?' in tl:
                    pat = tl.rsplit('/', 1)[-1]
                    if pat and fnmatch.fnmatch(filled, pat):
                        return True
        if n0 == 'find':
            for k, lt in enumerate(lits[:-1]):
                if lt in ('-name', '-iname', '-path', '-wholename'):
                    pat = ws[k + 2].lit() or tail_lit(ws[k + 2])
                    pat = pat.rsplit('/', 1)[-1] if pat else pat
                    if pat and fnmatch.fnmatch(filled, pat):
                        deletes = '-delete' in lits or any(
                            (lits[j] or '') in ('-exec', '-execdir') and j + 1 < len(lits) and
                            os.path.basename(lits[j + 1] or '') == 'rm' for j in range(len(lits)))
                        finds.append(deletes)
    return any(finds) or (bool(finds) and rm_var)


def has_exit_trap(sf):
    for c in sf.cmds:
        if c.name() == 'trap' and len(c.words) >= 3:
            sigs = [w.lit() or '' for w in c.words[2:]]
            if any(s in ('EXIT', '0', 'SIGEXIT') for s in sigs):
                return True
    return False


def check_file(sf):
    ctx = TmpCtx(sf)
    groups = {}            # 뿌리 id → [(줄, 비밀 이름, 명령)]
    for c in sf.cmds:
        cp = copy_pairs(c)
        if not cp:
            continue
        srcs, dest = cp
        rid = ctx.root_of(dest, c.func)
        if not rid:
            continue
        for w in srcs:
            sname = ctx.secret_of(w, c.func)
            if sname:
                groups.setdefault(rid, []).append((c.line, sname, c))
                break
    out, allowed = [], 0
    trap = has_exit_trap(sf)
    for rid, lst in groups.items():
        lst.sort(key=lambda x: x[0])
        name, mkline, tmpl = ctx.root_info(rid)
        if tmpl is None and name is not None:
            # 고정 경로 — 복사 전에 비우면 다음 실행이 같은 자리를 지운다
            first_seq = lst[0][2].seq
            if any(v == name and sq < first_seq for v, sq in ctx.cleared):
                continue
        if tmpl and has_stale_cleanup(sf, tmpl):
            continue
        marks = [ln for ln, _s, _c in lst] + ([mkline] if mkline else [])
        if any(sf.allowed(RULE, ln) for ln in marks):
            allowed += 1
            continue
        first = lst[0][0]
        others = sorted(set(ln for ln, _s, _c in lst[1:]) - {first})
        names = []
        for _ln, s, _c in lst:
            if s not in names:
                names.append(s)
        where = ('mktemp %d행' % mkline) if mkline else '임시 경로'
        more = (' · 같은 뿌리로 %d곳 더(%s행)' % (len(others), ','.join(str(x) for x in others[:6]))) if others else ''
        tail = ('정리는 EXIT trap 뿐이라 kill -9 로 끊기면 사본이 남는다' if trap else
                'EXIT trap 도 없어 끝나도 사본이 남는다')
        out.append(('낮음', sf.rel, first,
                    '비밀 파일(%s)을 임시 폴더(%s)로 복사%s — %s(다음 실행의 옛 폴더 청소나 받아들인 위험 표식 '
                    'qcheck-allow: R20 이 없다)' % ('·'.join(names[:3]), where, more, tail)))
    return out, allowed


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description='R20 비밀 파일을 임시 폴더로 복사 — 강제 종료 뒤 정리 길 없음(읽기만)')
    sh_common_args(ap, here)
    args = ap.parse_args(argv)
    st = sh_setup(RULE, args)
    if st is None:
        print('RESULT pass=0 fail=0 skip=1')
        return 2
    root, outer, files, skipped = st
    sfs, bad = sh_parse_all(RULE, files)
    skipped += bad
    findings = []
    for rel, sf in sfs.items():
        got, allowed = check_file(sf)
        findings.extend(got)
        skipped += allowed
    return sh_emit(RULE, findings, len(sfs), skipped)


